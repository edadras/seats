#!/usr/bin/env node
/**
 * Carries the check-in catalogue into the scanner.
 *
 * Everywhere else on the platform, a second copy of a translation is a bug: two copies is two
 * translations, and the wrong one is always the one nobody is looking at. The door scanner is the
 * one place where a copy is correct, and ADR-0005 says why — it has to work with no network, and a
 * catalogue it fetches is a catalogue it cannot fetch at the moment it is needed. A volunteer at a
 * door in Tehran cannot fix a missing string, and there is nobody there who could.
 *
 * So the copy is generated rather than written, from `api/lang/<locale>/checkin.php`, and CI runs
 * this and fails on a diff — the same discipline `tools/sync-seat-picker.sh` applies to the picker.
 * There is still exactly one file anybody edits.
 *
 * It also carries the facts about each locale that formatting needs — direction, digit shapes and
 * calendar — read from `Locales::ALL` rather than restated here, because a seventh language must
 * mean one edit and not two.
 *
 * Run: node tools/sync-checkin-strings.mjs
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'checkin-app', 'lib', 'l10n', 'strings.g.dart');
const page = path.join(root, 'checkin-app', 'web', 'index.html');

/**
 * Ask PHP for the whole thing at once.
 *
 * Shelling out rather than parsing the catalogues here for the same reason the i18n check does it:
 * these files are PHP, and a second half-parser would disagree with the real one on exactly the day
 * it mattered.
 */
const payload = JSON.parse(
	execFileSync(
		'php',
		[
			'-r',
			`
			require $argv[1] . '/app/Support/Locale/Locales.php';

			$out = ['locales' => [], 'messages' => []];

			foreach (\\App\\Support\\Locale\\Locales::ALL as $code => $facts) {
				$out['locales'][$code] = [
					'native' => $facts['native'],
					'dir' => $facts['dir'],
					'digits' => $facts['digits'],
					'calendar' => $facts['calendar'],
				];
				$out['messages'][$code] = require $argv[1] . '/lang/' . $code . '/checkin.php';
			}

			echo json_encode($out, JSON_UNESCAPED_UNICODE);
			`,
			path.join(root, 'api'),
		],
		{ encoding: 'utf8' }
	)
);

/** `a.b.c` keys, so the Dart side is one flat map and lookups are one string. */
function flatten(value, prefix = '', into = {}) {
	for (const [key, entry] of Object.entries(value)) {
		const full = prefix ? `${prefix}.${key}` : key;

		if (entry && typeof entry === 'object') {
			flatten(entry, full, into);
		} else {
			into[full] = String(entry);
		}
	}

	return into;
}

/** Dart single-quoted literal. Only three things can break one, and all three appear in these. */
const dart = (value) =>
	`'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;

const locales = Object.entries(payload.locales);
let source = `// GENERATED BY tools/sync-checkin-strings.mjs — DO NOT EDIT.
//
// The source is api/lang/<locale>/checkin.php. Edit that, run the tool, and commit both; CI runs
// the tool and fails on a diff. See the comment at the top of the tool for why the scanner carries
// a copy at all when nothing else on the platform does.

/// What formatting needs to know about a language, beyond its words.
class LocaleFacts {
  const LocaleFacts({
    required this.code,
    required this.native,
    required this.rtl,
    required this.digits,
    required this.persianCalendar,
  });

  final String code;

  /// The language's name in itself: somebody looking for Persian is looking for فارسی.
  final String native;

  final bool rtl;

  /// The ten digit glyphs this language's readers expect, in order, or null for Latin.
  final String? digits;

  final bool persianCalendar;
}

const List<LocaleFacts> kLocales = [
`;

for (const [code, facts] of locales) {
	const digits = { arabext: '۰۱۲۳۴۵۶۷۸۹', arab: '٠١٢٣٤٥٦٧٨٩' }[facts.digits] ?? null;

	source += `  LocaleFacts(
    code: ${dart(code)},
    native: ${dart(facts.native)},
    rtl: ${'rtl' === facts.dir},
    digits: ${digits ? dart(digits) : 'null'},
    persianCalendar: ${'persian' === facts.calendar},
  ),
`;
}

source += `];

const Map<String, Map<String, String>> kMessages = {
`;

for (const [code, messages] of Object.entries(payload.messages)) {
	source += `  ${dart(code)}: {\n`;

	for (const [key, value] of Object.entries(flatten(messages))) {
		source += `    ${dart(key)}: ${dart(value)},\n`;
	}

	source += `  },\n`;
}

source += `};\n`;

fs.mkdirSync(path.dirname(out), { recursive: true });

/*
 * The three words the *page* says before the engine has loaded anything.
 *
 * They go inline into index.html rather than into a file of their own: this runs before first
 * paint, and on the wifi this app is used on an extra request is the difference between a
 * translated boot screen and an English one nobody had time to read.
 */
const boot = Object.fromEntries(
	locales.map(([code, facts]) => [
		code,
		{
			dir: facts.dir,
			boot: payload.messages[code].boot,
			title: payload.messages[code].title,
		},
	])
);

const begin = '        // BEGIN GENERATED — tools/sync-checkin-strings.mjs writes this from api/lang/*/checkin.php';
const end = '        // END GENERATED';
const html = fs.readFileSync(page, 'utf8');
const from = html.indexOf(begin);
const to = html.indexOf(end);

if (from < 0 || to < 0) {
	throw new Error(`Could not find the generated block in ${path.relative(root, page)}`);
}

const rewritten =
	html.slice(0, from + begin.length) +
	`\n        var BOOT = ${JSON.stringify(boot)};\n` +
	html.slice(to);

const files = [
	[out, source],
	[page, rewritten],
];

let changed = 0;

for (const [file, contents] of files) {
	const before = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;

	if (before !== contents) {
		fs.writeFileSync(file, contents);
		changed++;
		console.log(`Wrote     ${path.relative(root, file)}`);
	}
}

const keys = Object.keys(flatten(payload.messages.en)).length;

console.log(`Locales:  ${locales.map(([code]) => code).join(', ')}`);
console.log(`Keys:     ${keys} per locale`);

if (!changed) {
	console.log('The copies were already in step.');
}
